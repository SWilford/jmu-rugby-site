-- S-06: Data-free baseline of the live Supabase schema.
--
-- This migration intentionally contains schema and configuration only. It does
-- not copy production users, administrator IDs, roster entries, media records,
-- or other site content.
--
-- The baseline is timestamped before the first tracked remediation migration so
-- a clean database can replay the complete migration chain in order.

create table public.admins (
  user_id uuid not null,
  created_at timestamptz not null default now(),
  constraint admins_pkey primary key (user_id),
  constraint admins_user_id_fkey
    foreign key (user_id) references auth.users(id) on delete cascade
);

create table public.coaches (
  id bigint not null,
  name text,
  position text,
  bio text,
  headshot_url text,
  constraint coaches_pkey primary key (id)
);

comment on table public.coaches is 'Coach information';

create table public.contact_cards (
  id bigint generated by default as identity,
  label text not null,
  value text not null,
  contact_type text not null default 'email',
  cta_label text,
  display_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint contact_cards_pkey primary key (id),
  constraint contact_cards_contact_type_check
    check (contact_type = any (array['email'::text, 'url'::text, 'phone'::text, 'text'::text]))
);

create table public.donate_content_settings (
