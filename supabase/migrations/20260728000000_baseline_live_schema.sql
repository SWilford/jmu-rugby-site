-- The bucket row is deployment configuration rather than website content.
-- ON CONFLICT keeps local resets compatible with config.toml bucket creation.
insert into storage.buckets (
  id,
  name,
  public,
  file_size_limit,
  allowed_mime_types
)
values (
  'rugby-media',
  'rugby-media',
  true,
  null,
  null
)
on conflict (id) do update
set
  name = excluded.name,
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

